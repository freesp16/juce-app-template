#!/usr/bin/env python3
"""Generate the GL dispatch stubs (platform/common/display/gldispatch, ADR-002, ADR-016).

  tools/gen-gl-dispatch.py [--arch arm|x86_64] <nm> <out_dir> <static libs...>

Scans the static libraries with `<nm> -u` for every EGL / GLES / Vivante-fb symbol they reference (names matching
^(egl|gl|fb)[A-Z]), drops the ones GlDispatch.cpp implements itself (OVERRIDES), and writes:

  <out_dir>/gldispatch_stubs.S   one stub per symbol that tail-jumps through gldispatch_table[i]. Arguments pass
                                 through untouched, so no signatures are needed.
                                   arm (default, the device): load the slot and `bx ip`
                                   x86_64 (the Linux desktop host): `jmp *gldispatch_table+8*i(%rip)`, position
                                   independent (the table is defined in the same executable)
  <out_dir>/gldispatch_names.inc the symbol names in table order, for gldispatch::load() to resolve with dlsym.

Because the list is derived from the objects at build time, it cannot go stale: a new GL call anywhere in the app or
in JUCE gets a stub on the next build.
"""
import pathlib
import re
import subprocess
import sys

SYMBOL = re.compile(r"^(egl|gl|fb)[A-Z]\w*$")
# Implemented in GlDispatch.cpp (EGL 1.5 -> 1.4 fallbacks, context retry, client-extension string, proc lookup).
OVERRIDES = {
    "eglGetPlatformDisplay", "eglGetPlatformDisplayEXT", "eglCreatePlatformWindowSurface",
    "eglCreatePlatformWindowSurfaceEXT", "eglQueryString", "eglCreateContext", "eglGetProcAddress",
}
# x86-64 (the Linux desktop) only: GlDispatch.cpp also implements eglGetDisplay there (#if __x86_64__), so the X11
# Display* is never guessed as a Wayland display by libglvnd/Mesa/NVIDIA when WAYLAND_DISPLAY is set.
OVERRIDES_X86_64 = {"eglGetDisplay"}


def arm_stubs(names):
    stubs = ["/* Generated by tools/gen-gl-dispatch.py. Do not edit. */",
             "    .syntax unified", "    .arm", "    .text",
             "    .macro GLSTUB name, index", "    .globl \\name", "    .type \\name, %function", "    .align 2",
             "\\name:", "    ldr ip, 1f", "    ldr ip, [ip, #(\\index * 4)]", "    bx ip",
             "1:  .word gldispatch_table", "    .size \\name, . - \\name", "    .endm", ""]
    stubs += [f"    GLSTUB {n}, {i}" for i, n in enumerate(names)]
    stubs += ["", '    .section .note.GNU-stack,"",%progbits', ""]
    return "\n".join(stubs)


def x86_64_stubs(names):
    stubs = ["/* Generated by tools/gen-gl-dispatch.py --arch x86_64. Do not edit. */",
             "    .text",
             "    .macro GLSTUB name, index", "    .globl \\name", "    .type \\name, @function", "    .p2align 4",
             "\\name:", "    jmp *gldispatch_table+8*\\index(%rip)",
             "    .size \\name, . - \\name", "    .endm", ""]
    stubs += [f"    GLSTUB {n}, {i}" for i, n in enumerate(names)]
    stubs += ["", '    .section .note.GNU-stack,"",@progbits', ""]
    return "\n".join(stubs)


def main() -> int:
    args = sys.argv[1:]
    arch = "arm"
    if args[:1] == ["--arch"]:
        arch, args = args[1], args[2:]
    if arch not in ("arm", "x86_64"):
        sys.exit(f"gen-gl-dispatch: unknown --arch {arch}")
    nm, out_dir, libs = args[0], pathlib.Path(args[1]), args[2:]
    names = set()
    for lib in libs:
        out = subprocess.run([nm, "-u", lib], check=True, capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if parts and SYMBOL.match(parts[-1]):
                names.add(parts[-1])
    names = sorted(names - OVERRIDES - (OVERRIDES_X86_64 if arch == "x86_64" else set()))
    out_dir.mkdir(parents=True, exist_ok=True)
    text = arm_stubs(names) if arch == "arm" else x86_64_stubs(names)
    inc = "/* Generated by tools/gen-gl-dispatch.py. Do not edit. */\n" + "".join(f'"{n}",\n' for n in names)
    for path, content in ((out_dir / "gldispatch_stubs.S", text), (out_dir / "gldispatch_names.inc", inc)):
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
    print(f"gl dispatch ({arch}): {len(names)} symbols, {len(OVERRIDES)} overrides")
    return 0


if __name__ == "__main__":
    sys.exit(main())
